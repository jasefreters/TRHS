/*
  Builds js/modules/numeracy-dash.js from The Daily Dash (github.com/jasefreters/mathswarmup).
  The numeracy modules' levels are NSW Stages (Level 1 = Stage 1, Level 2 = Stage 2, and so on).
  The Dash covers Stage 2 (Years 3–4) and Stage 3 (Years 5–6), so this builds Levels 2 and 3 from
  all of the Dash's units for that stage. Levels 1, 4 and 5 are written in the module files.

  Only questions that work without pictures are used: multiple choice, true/false, and short
  responses whose parts are typed numbers or choose-from-a-list. Each Dash question can become
  up to three items. Day 1 and Day 2 take different questions, spread across all loaded units.

  Run from the repo root, with the Daily Dash checked out next to it:
    node tools/dash-numeracy.js ../mathswarmup
  then bump ?v= in index.html and teacher.html.
*/
const fs = require("fs"), path = require("path");
const dash = path.resolve(process.argv[2] || "../mathswarmup");
global.window = global; global.UNITS = [];
for (const f of fs.readdirSync(path.join(dash, "units")).sort()) require(path.join(dash, "units", f));

const PER_SESSION = 12; // items per level per day: about 30 minutes
const STAGES = [{ level: 2, stage: 2, years: "3–4" }, { level: 3, stage: 3, years: "5–6" }];
const text = s => String(s).replace(/(\d+)\[(\d+)\/(\d+)\]/g, "$1 $2/$3").replace(/\[(\d+)\/(\d+)\]/g, "$1/$2");
const SKIP = ["img", "display", "table", "visual", "follow", "list"];

// Questions that talk about a picture or model the Dash draws on screen.
const VISUAL = /\b(strip|balance|shown|picture|diagram|image|drawing|this (array|prism|shape|graph|model|bar|object|net|angle|clock)|the (graph|table|map|grid|array|model|shape|clock))\b/i;

function convert(q) {
  if (SKIP.some(k => q[k]) || VISUAL.test(q.prompt)) return null;
  const prompt = text(q.prompt), explain = q.explain ? text(q.explain) : undefined;
  if (q.type === "mc") return [{ type: "mc", q: prompt, choices: q.options.map(text), answer: q.answer, explain }];
  if (q.type === "tf") return [{ type: "mc", q: `True or false? ${prompt}`, choices: ["True", "False"], answer: q.answer ? 0 : 1, explain }];
  const parts = q.interact || [];
  if (!parts.length || !parts.every(p => p.kind === "input" || p.kind === "choose")) return null;
  const out = [];
  for (const p of parts) {
    if (p.kind === "input") for (const f of p.fields || []) {
      if (typeof f.value !== "number") return null;
      const it = { type: "input", q: f.label ? `${prompt}\n\n**${text(f.label)}**` : prompt, answer: String(f.value) };
      if (f.accept) it.accept = f.accept.map(String);
      if (f.prefix) it.prefix = f.prefix;
      if (f.suffix) it.suffix = f.suffix;
      out.push(it);
    }
    if (p.kind === "choose" && p.rows.some(r => typeof r.a !== "number")) return null; // more than one right answer
    if (p.kind === "choose") for (const r of p.rows) out.push({ type: "mc", q: `${prompt}\n\n**${text(r.t)}**`, choices: r.options.map(text), answer: r.a });
  }
  if (!out.length || out.length > 3) return null;
  if (explain) out[out.length - 1].explain = explain;
  return out;
}

const result = { day1: {}, day2: {}, sources: {} };
for (const y of STAGES) {
  const units = UNITS.filter(u => u.stage === y.stage).sort((a, b) => a.ab.localeCompare(b.ab) || a.unit - b.unit);
  const pool = [];
  units.forEach(u => u.reviews.forEach(r => r.forEach(q => { const items = convert(q); if (items) pool.push({ unit: u.unit, items }); })));
  // Spread the picks across the whole pool; alternate questions between the two days.
  const pick = offset => {
    const chosen = [];
    const step = Math.max(2, Math.floor(pool.length / (PER_SESSION + 2)) * 2 || 2);
    for (let i = offset; i < pool.length && chosen.flat().length < PER_SESSION; i += step) chosen.push(pool[i].items);
    for (let i = offset; i < pool.length && chosen.flat().length < PER_SESSION; i += 2) if (!chosen.includes(pool[i].items)) chosen.push(pool[i].items);
    return chosen.flat().slice(0, PER_SESSION + 2);
  };
  result.day1[y.level] = pick(0);
  result.day2[y.level] = pick(1);
  result.sources[y.level] = `Stage ${y.stage} (Years ${y.years}): units ${units.map(u => u.ab + u.unit).join(", ")}`;
  console.log(`Level ${y.level} (Stage ${y.stage}): ${pool.length} usable questions; day 1 ${result.day1[y.level].length} items, day 2 ${result.day2[y.level].length} items`);
}
const file = `/*
  Generated by tools/dash-numeracy.js from The Daily Dash. Don't edit by hand: change the Dash
  and run the tool again. Questions adapted from NSW Department of Education Mathematics
  Stage 2 and Stage 3 Review of learning resources, © State of New South Wales (Department of
  Education), CC BY 4.0.
*/
window.RP = window.RP || {};
RP.DASH_NUMERACY = ${JSON.stringify(result, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "modules", "numeracy-dash.js"), file);
